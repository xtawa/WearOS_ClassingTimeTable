const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require(process.env.JSDOM_MODULE || 'jsdom');
const html = fs.readFileSync(path.join(__dirname, '../docs/exams/preview.html'), 'utf8');
const dom = new JSDOM(html, { runScripts: 'dangerously', beforeParse(window) {
  window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  window.confirm = () => true;
} });
const { document, Event } = dom.window;
const byId = id => document.getElementById(id);
const submit = () => byId('form').dispatchEvent(new Event('submit', { cancelable: true }));
byId('exam').click();
assert.equal(byId('exam').getAttribute('aria-selected'), 'true');
assert(!byId('examPanel').classList.contains('hidden'));
byId('exams').querySelector('button').click();
byId('location').value = 'B205'; byId('cancel').click();
assert(byId('exams').textContent.includes('B204'));
byId('exams').querySelector('button').click();
byId('location').value = 'B205'; submit();
assert(byId('exams').textContent.includes('B205'));
assert(byId('watchTime').textContent.includes('B205'));
byId('add').click(); byId('title').value = 'Invalid'; byId('end').value = '08:00'; submit();
assert(byId('error').textContent.length > 0);
assert.equal(byId('exams').querySelectorAll('article').length, 1);
byId('end').value = '11:00'; byId('title').value = '<img src=x onerror=alert(1)>'; submit();
assert.equal(byId('exams').querySelectorAll('article').length, 2);
assert.equal(byId('exams').querySelectorAll('img').length, 0);
while (byId('exams').querySelector('article')) byId('exams').querySelectorAll('button')[1].click();
assert(byId('exams').textContent.includes('暂无考试'));
assert.equal(byId('watchTitle').textContent, '暂无考试');
byId('ai').click(); assert(byId('aiStatus').textContent.includes('确认'));
byId('schedule').click(); assert.equal(byId('watchTitle').textContent, 'Computer Science');
assert.equal(byId('schedule').getAttribute('aria-selected'), 'true');
dom.window.close();
console.log('PASS: exam toggle, cancel, save, watch preview, invalid time, escaped title, empty state and AskAI confirmation notice');
